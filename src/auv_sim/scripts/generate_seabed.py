#!/usr/bin/env python3
"""Generate the seabed mesh as a Wavefront OBJ file.

The surface is a sum of a few sine waves plus small repeatable noise, so the
sonar is getting some geometry to match against and the same mesh comes out in
every build.
"""

import argparse
import math


def height(x, y, depth):
    z = depth
    z += 1.2 * math.sin(x / 9.0) * math.cos(y / 7.0)        # long dunes
    z += 0.5 * math.sin(x / 3.1 + 1.0) * math.sin(y / 2.7)  # short ripples
    z += 0.02 * x                                            # gentle slope
    # hash based noise, repeatable without any seed handling
    n = math.sin(x * 12.9898 + y * 78.233) * 43758.5453
    z += 0.12 * ((n - math.floor(n)) - 0.5)
    return z


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--out', required=True, help='output .obj path')
    parser.add_argument('--size', type=float, default=100.0, help='side length in m')
    parser.add_argument('--step', type=float, default=1.0, help='grid spacing in m')
    parser.add_argument('--depth', type=float, default=-10.0, help='mean seabed z in m')
    args = parser.parse_args()

    n = int(round(args.size / args.step)) + 1
    half = args.size / 2.0
    coords = [-half + i * args.step for i in range(n)]

    heights = [[height(x, y, args.depth) for x in coords] for y in coords]

    def h(row, col):
        return heights[min(max(row, 0), n - 1)][min(max(col, 0), n - 1)]

    with open(args.out, 'w') as f:
        f.write('# seabed mesh, generated by generate_seabed.py\n')
        f.write('o seabed\n')
        for row, y in enumerate(coords):
            for col, x in enumerate(coords):
                f.write(f'v {x:.3f} {y:.3f} {heights[row][col]:.3f}\n')

        # normals from central differences
        for row in range(n):
            for col in range(n):
                dzdx = (h(row, col + 1) - h(row, col - 1)) / (2.0 * args.step)
                dzdy = (h(row + 1, col) - h(row - 1, col)) / (2.0 * args.step)
                norm = math.sqrt(dzdx * dzdx + dzdy * dzdy + 1.0)
                f.write(f'vn {-dzdx / norm:.4f} {-dzdy / norm:.4f} {1.0 / norm:.4f}\n')

        # two triangles per grid cell, counter clockwise when seen from above
        for row in range(n - 1):
            for col in range(n - 1):
                a = row * n + col + 1
                b = a + 1
                c = a + n
                d = c + 1
                f.write(f'f {a}//{a} {b}//{b} {d}//{d}\n')
                f.write(f'f {a}//{a} {d}//{d} {c}//{c}\n')


if __name__ == '__main__':
    main()
